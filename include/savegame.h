// A one-past record identity may share an address with a different owner's
// actual start. Resolve every concrete object family before field/end views.

bool pt_saved_pointer_identity(const void *, guest_ptr32 *);
static inline guest_ptr32 pt_buffer_to_guest(const void *pointer) {
  if (!pointer)
    return 0;
  guest_ptr32 object_address;
  if (pt_saved_pointer_identity(pointer, &object_address))
    return object_address;
  uintptr_t address = (uintptr_t)pointer - (uintptr_t)pt_memory.bytes;
  if (address > UINT32_MAX && (uintptr_t)pt_memory.bytes - (uintptr_t)pointer > UINT32_MAX)
    abort();
  return (guest_ptr32)address;
}

